package main

import (
	"fmt"
	"go/format"
	"sort"
	"strings"
)

func emit(m *model, version string) ([]byte, error) {
	seen := make(map[string]string)
	claim := func(name, origin string) error {
		if prev, ok := seen[name]; ok {
			return fmt.Errorf("generated identifier %s is used by both %s and %s", name, prev, origin)
		}
		seen[name] = origin
		return nil
	}

	metricNames := sortedKeys(m.metrics)
	attrIDs := sortedKeys(m.attrs)

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by internal/schema/gen from semconv %s; DO NOT EDIT.\n\npackage schema\n", version)

	b.WriteString("\nconst (\n")
	for _, name := range metricNames {
		id := ident(name)
		if err := claim(id, "metric "+name); err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "\t%s = %q\n", id, name)
	}
	b.WriteString(")\n")

	b.WriteString("\nconst (\n")
	for _, attrID := range attrIDs {
		id := "Attr" + ident(attrID)
		if err := claim(id, "attribute "+attrID); err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "\t%s = %q\n", id, attrID)
	}
	b.WriteString(")\n")

	type enumConst struct {
		name  string
		value string
	}
	var enums []enumConst
	for _, attrID := range attrIDs {
		def := m.attrs[attrID]
		for _, member := range def.Members {
			enums = append(enums, enumConst{name: member.Const, value: member.Value})
		}
	}
	sort.Slice(enums, func(i, j int) bool { return enums[i].name < enums[j].name })

	b.WriteString("\nconst (\n")
	for _, enum := range enums {
		if err := claim(enum.name, "member "+enum.value); err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "\t%s = %q\n", enum.name, enum.value)
	}
	b.WriteString(")\n")

	b.WriteString("\nvar metrics = []MetricDef{\n")
	for _, name := range metricNames {
		def := m.metrics[name]
		fmt.Fprintf(&b, "\t{Name: %s, Unit: %q, Kind: Kind%s", ident(name), def.Unit, def.Kind)
		if len(def.Attrs) > 0 {
			b.WriteString(", Attrs: []AttrDef{")
			for i, attrID := range def.Attrs {
				if i > 0 {
					b.WriteString(", ")
				}
				fmt.Fprintf(&b, "{Name: Attr%s", ident(attrID))
				if values := m.attrs[attrID].Values; len(values) > 0 {
					consts := make([]string, 0, len(values))
					for _, member := range m.attrs[attrID].Members {
						consts = append(consts, member.Const)
					}
					b.WriteString(", Values: []string{")
					b.WriteString(strings.Join(consts, ", "))
					b.WriteString("}")
				}
				b.WriteString("}")
			}
			b.WriteString("}")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")

	b.WriteString("\nfunc Lookup(name string) (MetricDef, bool) {\n")
	b.WriteString("\tfor i := range metrics {\n")
	b.WriteString("\t\tif metrics[i].Name == name {\n")
	b.WriteString("\t\t\treturn metrics[i], true\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn MetricDef{}, false\n")
	b.WriteString("}\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}
	return src, nil
}
